import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (msg) => { if (msg.type() === 'error' && !msg.text().includes('favicon')) errors.push(msg.text()); });
const checks = [];
try {
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5176', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => window.__chronos?.ready && window.__chronos.frames > 30, { timeout: 45000 });
  checks.push('WebGL scene initializes and renders more than 30 frames');
  await page.screenshot({ path: 'test-results/desktop.png' });
  await page.locator('#pause').click();
  let stats = await page.evaluate(() => window.__chronos);
  assert.equal(stats.paused, true);
  const t = stats.time;
  await page.waitForTimeout(350);
  assert.equal((await page.evaluate(() => window.__chronos)).time, t);
  checks.push('Pause freezes simulation time');
  await page.locator('#time-speed').evaluate((el) => { el.value = '-1.5'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  assert.equal((await page.evaluate(() => window.__chronos)).speed, -1.5);
  await page.waitForTimeout(400);
  assert.ok((await page.evaluate(() => window.__chronos)).time < t);
  checks.push('Negative time speed reverses simulation');
  await page.locator('#pause').click();
  stats = await page.evaluate(() => window.__chronos);
  const memory = stats.memoryPositions.find((m) => m.x > 80 && m.x < 1250 && m.y > 180 && m.y < 700);
  assert.ok(memory, 'A clickable memory must be in the viewport');
  await page.mouse.click(memory.x, memory.y);
  await page.waitForTimeout(250);
  assert.equal((await page.evaluate(() => window.__chronos)).collected, 1);
  checks.push('Clicking a 3D memory increments collection counter');
  for (let i = 0; i < 4; i++) {
    const remaining = (await page.evaluate(() => window.__chronos)).memoryPositions.find((m) => !m.collected && m.x > 20 && m.x < 1400 && m.y > 100 && m.y < 750);
    assert.ok(remaining, 'Remaining memory must be clickable');
    await page.mouse.click(remaining.x, remaining.y);
    await page.waitForTimeout(80);
  }
  assert.equal((await page.evaluate(() => window.__chronos)).collected, 5);
  assert.ok((await page.locator('#memory-caption h2').textContent()).includes('余下的光'));
  checks.push('All five memories can be collected and reveal the final message');
  await page.locator('#rebirth').click();
  stats = await page.evaluate(() => window.__chronos);
  assert.equal(stats.cycles, 1); assert.equal(stats.collected, 0); assert.equal(stats.paused, false);
  checks.push('Rebirth triggers pulse and resets memory collection');
  await page.waitForTimeout(1100);
  await page.screenshot({ path: 'test-results/rebirth.png' });
  await page.locator('#help').click();
  assert.equal(await page.locator('#help-dialog').evaluate((el) => el.open), true);
  await page.locator('#close-help').click();
  checks.push('Instructions dialog opens and closes');
  await page.locator('#quality').click();
  assert.equal((await page.evaluate(() => window.__chronos)).quality, 1);
  await page.locator('#quality').click();
  assert.equal((await page.evaluate(() => window.__chronos)).quality, 2);
  checks.push('Quality presets switch without runtime errors');
  await page.locator('#sound').click();
  assert.equal(await page.locator('#sound-label').textContent(), '声音 开');
  await page.locator('#sound').click();
  checks.push('Procedural audio toggles on and off');
  await page.locator('#reset').click();
  stats = await page.evaluate(() => window.__chronos);
  assert.equal(stats.speed, 1); assert.equal(stats.paused, false);
  checks.push('Reset restores camera and speed');
  const before = stats.camera;
  await page.mouse.move(850, 450); await page.mouse.down(); await page.mouse.move(1000, 490, { steps: 15 }); await page.mouse.up();
  await page.waitForTimeout(500);
  assert.notDeepEqual((await page.evaluate(() => window.__chronos)).camera, before);
  checks.push('Mouse drag orbits camera');
  const afterDrag = (await page.evaluate(() => window.__chronos)).camera;
  await page.mouse.wheel(0, -300); await page.waitForTimeout(500);
  assert.notDeepEqual((await page.evaluate(() => window.__chronos)).camera, afterDrag);
  checks.push('Mouse wheel zooms');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#reset').click();
  await page.waitForTimeout(700);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'test-results/mobile.png' });
  checks.push('390px mobile viewport renders without horizontal overflow');
  assert.equal(errors.length, 0, errors.join('\n'));
  checks.push('No JavaScript or shader compilation errors');
  console.log(JSON.stringify({ passed: true, checks, stats: await page.evaluate(() => window.__chronos), errors }, null, 2));
  await writeFile('test-results/report.json', JSON.stringify({ passed: true, checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: 'test-results/failure.png' });
  console.error(JSON.stringify({ passed: false, checks, errors, failure: error.message }, null, 2));
  throw error;
} finally { await browser.close(); }
